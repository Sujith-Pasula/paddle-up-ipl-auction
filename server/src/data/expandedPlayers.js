const slugify = s => s.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const hash = s => { let h=2166136261; for(const ch of s){h^=ch.charCodeAt(0);h=Math.imul(h,16777619)} return Math.abs(h>>>0); };
const avatar = name => `https://ui-avatars.com/api/?name=${encodeURIComponent(name)}&background=0b1712&color=fff&bold=true&size=512`;
const existing = new Set();
const profiles = [];
for (const line of names.trim().split('\n')) {
  const [name, role] = line.split('|');
  const id = slugify(name);
  if (existing.has(id)) continue;
  existing.add(id);
  const h = hash(id);
  const base = role === 'Batsman' ? 0.5 + (h % 5) * 0.25 : role === 'Bowler' ? 0.5 + (h % 5) * 0.25 : role === 'Wicket-Keeper' ? 0.5 + (h % 5) * 0.25 : 0.5 + (h % 6) * 0.25;
  const rating = 67 + (h % 22);
  const batting = role === 'Bowler' ? 18 + (h % 30) : role === 'Wicket-Keeper' ? 72 + (h % 22) : 70 + (h % 27);
  const bowling = role === 'Batsman' || role === 'Wicket-Keeper' ? 8 + (h % 24) : 65 + (h % 30);
  const fielding = 68 + (h % 29);
  profiles.push({ id, name, role, basePrice: Number(base.toFixed(2)), rating, nationality:'International/India', batting, bowling, fielding, photo:avatar(name), previousTeams:[], category:role, expandedPool:true });
}
export const EXPANDED_PLAYERS = profiles;
